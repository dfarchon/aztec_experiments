#!/usr/bin/env node
// ============================================================
// extract_thread_worker.cjs
//
// Extracts the minimal code needed for Barretenberg thread workers
// from the 55MB aztec_bundle.js, producing a small (~100KB)
// thread_worker.js that can be spawned by createThreadWorker()
// WITHOUT loading the entire 55MB bundle per worker.
//
// The thread worker needs only:
//   1. comlink expose() + dependencies
//   2. randomBytes()
//   3. BarretenbergWasmBase class
//   4. BarretenbergWasmThread class
//   5. Worker bootstrap (expose + postMessage ready)
// ============================================================

const fs = require('fs');
const path = require('path');

const BUNDLE = path.join(__dirname, 'aztec_bundle.js');
const OUTPUT = path.join(__dirname, 'thread_worker.js');

const src = fs.readFileSync(BUNDLE, 'utf8');
const lines = src.split('\n');

// Helper: find line index (0-based) of a line containing a substring
function findLine(needle, startFrom = 0) {
  for (let i = startFrom; i < lines.length; i++) {
    if (lines[i].includes(needle)) return i;
  }
  throw new Error(`Not found: ${needle}`);
}

// 1. Extract comlink code: from the comlink comment to the helpers/browser comment
const comlinkStart = findLine('// node_modules/comlink/dist/esm/comlink.mjs');
const comlinkEnd = findLine('// node_modules/@aztec-foundation/bb.js/dest/browser/barretenberg_wasm/helpers/browser/index.js', comlinkStart);
const comlinkCode = lines.slice(comlinkStart, comlinkEnd).join('\n');

// 2. Extract randomBytes (use brace-depth tracking, not first '};')
const rbStart = findLine('var randomBytes = (len) => {');
let rbEnd = rbStart + 1;
let rbDepth = 0;
for (let i = rbStart; i < lines.length; i++) {
  for (const ch of lines[i]) {
    if (ch === '{') rbDepth++;
    if (ch === '}') rbDepth--;
  }
  if (rbDepth === 0 && i > rbStart) {
    rbEnd = i + 1;
    break;
  }
}
const randomBytesCode = lines.slice(rbStart, rbEnd).join('\n');

// 3. Extract BarretenbergWasmBase
const baseStart = findLine('var BarretenbergWasmBase = class');
let baseEnd = baseStart + 1;
// Find the closing }; of the class (look for the next line that is just "  };" at class scope)
let braceDepth = 0;
for (let i = baseStart; i < lines.length; i++) {
  for (const ch of lines[i]) {
    if (ch === '{') braceDepth++;
    if (ch === '}') braceDepth--;
  }
  if (braceDepth === 0 && i > baseStart) {
    baseEnd = i + 1;
    break;
  }
}
const baseCode = lines.slice(baseStart, baseEnd).join('\n');

// 4. BarretenbergWasmThread class (written directly, not extracted — it's our patch)
const threadClassCode = `
var BarretenbergWasmThread = class extends BarretenbergWasmBase {
  async initThread(module, memory, useCustomLogger = false) {
    this.logger = useCustomLogger
      ? ((msg) => { try { postMessage({ type: "log", msg: String(msg) }); } catch(e) {} })
      : ((msg) => { try { console.log(msg); } catch(e) {} });
    this.memory = memory;
    this.instance = await WebAssembly.instantiate(module, this.getImportObj(this.memory));
  }
  destroy() { try { self.close(); } catch(e) {} }
  getImportObj(memory) {
    const baseImports = super.getImportObj(memory);
    return {
      ...baseImports,
      wasi: {
        'thread-spawn': () => {
          this.logger('PANIC: threads cannot spawn threads!');
          try { self.close(); } catch(e) {}
        }
      },
      env: {
        ...baseImports.env,
        env_hardware_concurrency: () => 1
      }
    };
  }
};
`;

// 5. Assemble the thread worker file
const output = `// thread_worker.js — Auto-generated by extract_thread_worker.cjs
// Minimal Barretenberg thread worker (~16KB vs 55MB full bundle).
// Do not edit manually; re-run: node shared/extract_thread_worker.cjs
(function() {
  'use strict';

  // --- Stubs for bundle-internal functions not included in this minimal worker ---
  function init_inject_globals() {}
  var __toESM = (m) => m;
  function require_buffer() { return { Buffer: typeof Buffer !== 'undefined' ? Buffer : class Buffer extends Uint8Array {} }; }
  function require_browser() { return { default: typeof process !== 'undefined' ? process : { nextTick: (fn) => setTimeout(fn, 0) } }; }
  // Minimal Buffer polyfill if not already present
  if (typeof globalThis.Buffer === 'undefined') {
    globalThis.Buffer = require_buffer().Buffer;
  }
  if (typeof globalThis.process === 'undefined') {
    globalThis.process = require_browser().default;
  }
  // --- esbuild helper functions used by BarretenbergWasmBase ---
  var __defProp = Object.defineProperty;
  var __defNormalProp = (obj, key, value) => key in obj ? __defProp(obj, key, { enumerable: true, configurable: true, writable: true, value }) : obj[key] = value;
  var __publicField = (obj, key, value) => __defNormalProp(obj, typeof key !== "symbol" ? key + "" : key, value);

  // --- comlink (expose + dependencies) ---
${comlinkCode}

  // --- randomBytes ---
${randomBytesCode}

  // --- BarretenbergWasmBase ---
${baseCode}

  // --- BarretenbergWasmThread ---
${threadClassCode}

  // --- Worker bootstrap ---
  try {
    expose(new BarretenbergWasmThread());
    postMessage({ ready: true });
  } catch(e) {
    try { console.error('[thread_worker bootstrap]', e); } catch(e2) {}
  }
})();
`;

fs.writeFileSync(OUTPUT, output);
const sizeKB = Math.round(Buffer.byteLength(output) / 1024);
console.log(`Extracted thread worker: ${OUTPUT} (${sizeKB}KB)`);
console.log(`  comlink:      ${comlinkEnd - comlinkStart} lines`);
console.log(`  randomBytes:  ${rbEnd - rbStart} lines`);
console.log(`  WasmBase:     ${baseEnd - baseStart} lines`);
